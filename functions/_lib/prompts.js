    '- 사진을 다 읽은 뒤에, 아래 형식으로 정리·분석합니다. (충분히 읽지 않고 추측으로 값을 채우면 안 됩니다.)',
    '',
    '## 출력 분량 규칙 (매우 중요 · 반드시 지킬 것)',
    '- 전체를 간결하게, 핵심만 개조식(하이픈)으로. 서술형 문장·인사말·사족·같은 말 반복 금지.',
